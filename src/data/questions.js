// 获取指定模型的题目
export function getQuestionsByModelId(modelId) {
  return questionBank[modelId]
}

// 随机抽取题目（用于组卷）
export function getRandomQuestions(model, count = 3) {
  // 优先使用专用题库
  const allQuestions = getQuestionsByModelId(model.id)
  if (allQuestions && allQuestions.length > 0) {
    // 如果题库题目数量不足，返回所有题目
    if (allQuestions.length <= count) {
      return allQuestions
    }
    // 随机抽取
    const shuffled = [...allQuestions].sort(() => Math.random() - 0.5)
    return shuffled.slice(0, count)
  }
  // 如果没有专用题库，生成通用题目
  return generateGenericQuestions(model)
}

// 计算得分
export function calculateScore(answers, questions) {
  let score = 0
  answers.forEach((answer, index) => {
    if (answer === questions[index].correct) {
      score += 10
    }
  })
  return score
}
